<?php

namespace App\Services\Ai;

/**
 * Чистка тексту, який бачить модель або клієнт.
 * Винесено з AiAgentService: чисті функції без стану й залежностей.
 */
class TextScrubber
{
    /**
     * Внутрішні назви лінійок (вигадані для CRM, клієнти їх не знають).
     * Вирізаються з УСЬОГО, що бачить модель: каталог, картки, історія.
     * Модель не може сказати слово, якого ніколи не бачила.
     */
    private const INTERNAL_WORDS = ['halluci', 'luxury'];

    /** Прибрати службові слова з тексту для моделі. */
    public function scrub(?string $text): ?string
    {
        if ($text === null || $text === '') {
            return $text;
        }
        $clean = preg_replace('/(?:' . implode('|', self::INTERNAL_WORDS) . ')/iu', '', $text);
        return trim(preg_replace('/[ \t]{2,}/u', ' ', $clean));
    }

    /**
     * Вирізати плейсхолдер фото («[зображення]» тощо). Фото шле лише send_photos;
     * якщо модель надрукувала позначку текстом — клієнт побачив би сміття.
     * Чистимо і вихідний текст, і історію (щоб модель не копіювала позначку далі).
     */
    public function stripPhotoPlaceholder(?string $text): string
    {
        $clean = preg_replace('/\[\s*(?:зображення|фото|image|photo|картинк[аи])\s*\]/iu', '', (string) $text);
        // Службова примітка памʼяті про надіслані фото — лише для історії бота; якщо
        // модель написала подібне у відповіді — вирізаємо В БУДЬ-ЯКОМУ формулюванні
        // («товару»/«товарів», зі «(система: …)» чи без), щоб не злити клієнту.
        // Кейс Тані Ковальчук 04.07: модель написала «фото товарУ», фільтр «товарІВ» промазав.
        $clean = preg_replace(self::SENT_PHOTOS_NOTE_RE, '', (string) $clean);
        return trim(preg_replace('/\n{3,}/u', "\n\n", (string) $clean));
    }

    /** Службова позначка «надіслала … фото …» в дужках — у будь-якому написанні. */
    private const SENT_PHOTOS_NOTE_RE = '/\(\s*(?:система:\s*)?(?:ти\s+)?(?:вже\s+)?надісла[^)]*фото[^)]*\)/iu';

    /**
     * Артефакти моделі, які месенджер показує клієнту як сміття (з'явились із
     * Sonnet, кейси 05.07): markdown-розмітка (**жирний**, `бектики`, ## заголовки)
     * FB/IG не рендерять — клієнт бачить зірочки; а галюцинована «продовжена
     * розмова» («Human: є розміри 38,40?») — взагалі чужа репліка в чаті.
     * Фільтр детермінований: працює незалежно від моделі й промпту.
     */
    public function stripModelArtifacts(?string $text): string
    {
        $clean = (string) $text;

        // Галюцинований діалог: відрізаємо ВСЕ від рядка «Human:»/«Assistant:»/«User:».
        // Кейс Olena Lykova 09.07 (Opus): «user Домашні» — без двокрапки й з малої
        // літери, тому двокрапка необовʼязкова (досить пробілу після ролі),
        // а збіг регістронезалежний. Українських слів ці ролі не зачіпають.
        $clean = preg_replace('/\n\s*(?:Human|Assistant|User)(?:\s*:|[ \t]).*$/siu', '', $clean);

        // Markdown-емфаза: **жирний** / __жирний__ → чистий текст (одинарні * не чіпаємо).
        $clean = preg_replace('/\*\*(.+?)\*\*/su', '$1', $clean);
        $clean = preg_replace('/__(.+?)__/su', '$1', $clean);
        $clean = str_replace('**', '', $clean);

        // `бектики` і ## заголовки на початку рядка.
        $clean = preg_replace('/`([^`\n]*)`/u', '$1', $clean);
        $clean = preg_replace('/^#{1,4}\s+/mu', '', $clean);

        return trim($clean);
    }

    /**
     * Модель ЗАЯВЛЯЄ в тексті, що показує/надсилає фото (службова позначка в дужках,
     * плейсхолдер «[фото]» або обіцянка від першої особи). Разом із фактом
     * «send_photos не викликано» це сигнал ПЕРЕРОБИТИ відповідь через API:
     * фото шле лише інструмент, слова фото не надсилають.
     */
    public function mentionsSendingPhotos(?string $text): bool
    {
        $t = (string) $text;
        if ($t === '') {
            return false;
        }

        return (bool) (
            preg_match(self::SENT_PHOTOS_NOTE_RE, $t)
            || preg_match('/\[\s*(?:зображення|фото|image|photo|картинк[аи])\s*\]/iu', $t)
            || preg_match('/\b(?:надсилаю|надішлю|відправляю|скидаю)\b[^.\n!?]{0,40}?\b(?:фото|колаж|картинк)/iu', $t)
            || preg_match('/\bось\s+(?:детальн\w+\s+|наш\w*\s+)?(?:фото|колаж)/iu', $t)
        );
    }
}
