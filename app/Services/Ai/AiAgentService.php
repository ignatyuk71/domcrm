        return array_merge($this->productSummary($p, $this->photoInfoFor([$p->id])), [
            'опис' => $this->scrub($p->description ?: null),
            'розміри' => $p->variants->map(fn ($v) => [
                'розмір' => $v->size,
                'залишок' => (int) $v->stock_qty,
