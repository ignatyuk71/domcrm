    public static function clockNote(): string
    {
        $now = now();
        $days = ['неділя', 'понеділок', 'вівторок', 'середа', 'четвер', "п'ятниця", 'субота'];
        $part = match (true) {
            $now->hour >= 6 && $now->hour < 11 => 'ранок',
            $now->hour >= 11 && $now->hour < 17 => 'день',
            $now->hour >= 17 && $now->hour < 23 => 'вечір',
            default => 'ніч',
        };

        // НЕ пиши тут наказ «вітайся» — Sonnet виконує його щоходу і вітається
        // повторно (кейс 06.07: «добрий вечір» 3 рази). Лише УМОВА про формат.
        return sprintf(
            '(система: зараз %s, %s, %s — %s. Якщо в розмові ВЖЕ було наше привітання — НЕ вітайся знову, відповідай одразу по суті. Вітальні слова доречні ЛИШЕ у найпершій нашій репліці; тоді бери їх за часом доби (ранок/день — «Доброго дня», вечір — «Доброго вечора», ніч — «Доброї ночі»). «Відправимо сьогодні» обіцяй лише якщо ще НЕ минуло 12:00 і сьогодні не неділя — інакше чесно кажи, що відправка наступного робочого дня.)',
            $days[$now->dayOfWeek],
            $now->format('d.m.Y'),
            $now->format('H:i'),
            $part
        );
    }

