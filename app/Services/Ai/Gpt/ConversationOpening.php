    /** Звичайна консультація продовжується без передачі людині. */
    public static function isAdvice(InboxMessage $message): bool
    {
        $text = (string) $message->text;
        if (preg_match('/(?:менеджер|оператор|людин|консультант|поверн|обмін|скарг|брак)/iu', $text)) return false;

        return (bool) preg_match('/(?:кращ|лучше|порад|посовет|рекоменд|взяти|брати|обрати|обрать|обер|підій|подойд|розмір|размер|стоп|устіл|бортик|тісн|замал|завелик|замовит|заказать|цін|цен|вартіст|наяв|налич|колір|цвет|фото|покаж)/iu', $text);
    }

    /** Зберігаємо надані сантиметри й у наступних питаннях про вибір розміру. */
    public static function footLength(InboxConversation $conversation, InboxMessage $message): ?string
    {
        $rows = $conversation->messages()->when($conversation->ai_context_after_id,
            fn ($q, $id) => $q->where('id', '>', $id))->where('id', '<=', $message->id)->latest('id')->limit(30)->get()->reverse();
        $known = $conversation->ai_checkout_data['sizing']['foot_length_cm'] ?? null;
        $asked = false;
        $currentIsMeasurement = false;
        foreach ($rows as $row) {
            if ($row->direction === 'out') {
                if (preg_match_all('/[^.!?\n]*\?/u', (string) $row->text, $questions)) {
                    $asked = (bool) preg_match('/(?:довжин\p{L}*|скільки|який).*(?:стоп|устіл|сантиметр|см)/iu', end($questions[0]));
                }
                continue;
            }
            if ($asked && preg_match('/^\s*(?:(?:(?:у|в)\s+мене|у\s+меня|(?:моя\s+)?стопа|довжина\s+стопи)\s*[:—-]?\s*)?(\d{1,2}(?:[.,]\d{1,2})?)\s*(?:см|cm|сантиметр\p{L}*)?\s*[.!]?\s*$/iu', (string) $row->text, $match)) {
                $known = str_replace(',', '.', $match[1]);
                $asked = false;
                if ($row->id === $message->id) $currentIsMeasurement = true;
            }
        }

        return $currentIsMeasurement || self::isAdvice($message) ? $known : null;
    }

    public static function reply(InboxConversation $conversation, InboxMessage $message): ?string
    {
        if ($message->attachments || $message->context) {
            return null;
        }
        $text = trim(preg_replace('/[^\p{L}\p{N}]+/u', ' ', mb_strtolower(trim((string) $message->text))));
        if ($text === '' || mb_strlen($text) > 100) {
            return null;
        }
        $greeting = '(?:привіт(?:ик)?|вітаю|добрий (?:день|вечір|ранок)|доброго (?:дня|вечора|ранку)|здравствуйте|здрастуйте|добрый (?:день|вечер)|hello|hi|hey)';
        $remainder = trim(preg_replace('/^'.$greeting.'(?:\s+|$)/u', '', $text));
        $contactCheck = preg_match('/^(?:алло|ау|агов|ви тут|є хто|є хтось|хто тут)$/u', $remainder);
        $fragment = preg_match('/^(?:(?:а|і|й|та|але|ну|до|від|на|за|у|в|з|із|зі|про|по|для|або|щодо|як|якщо)(?:\s+|$))+$/u', $remainder);
        if ($remainder !== '' && ! $contactCheck && ! $fragment) {
            return null;
        }

        // Перевіряємо початок розмови, щоб не повторювати привітання після відновлення.
        $greeted = $conversation->messages()->where('direction', 'out')->oldest('id')->limit(20)->pluck('text')
            ->contains(fn ($text) => preg_match('/(?:привіт|вітаю|доброго (?:дня|вечора|ранку)|добрий (?:день|вечір|ранок))/iu', (string) $text));
        $hello = $greeted ? '' : match (true) {
            now()->hour >= 6 && now()->hour < 17 => 'Доброго дня! ',
            now()->hour >= 17 && now()->hour < 23 => 'Доброго вечора! ',
            default => 'Доброї ночі! ',
        };

        return $hello.($remainder === '' ? 'Підкажіть, що вас цікавить 🙂' : 'Уточніть, будь ласка, що саме вас цікавить 🙂');
    }
