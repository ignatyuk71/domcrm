<?php

namespace App\Modules\Gpt\Domain;

class CatalogQuery
{
    /** Кожне слово має збігтися, варіанти всередині слова — взаємозамінні. */
    public function terms(string $query): array
    {
        $query = preg_replace('~https?://\S+|(?:^|\n)Фото:.*~iu', ' ', $query);
        preg_match_all('~[\p{L}\p{N}]+(?:[-\x{2013}\x{2014}][\p{L}\p{N}]+)*~u', mb_strtolower($query), $matches);
        $ignored = array_flip(explode(' ', 'привіт вітаю добрий доброго день дня вечір вечора дякую спасибі будь ласка будьласка чи є у в ви вас ваші ваш який яка які яке яких як а і й та або мені мене ми я хочу хотів хотіла потрібно потрібні треба можна можете покажи покажіть підкажи підкажіть скажи скажіть знайди знайдіть шукати шукаю купити замовити ціна ціни ціну ціною вартість скільки коштує коштують ці розмір розміри розмірі розміру кольори колір кольору наявність наявності наявні наявне наявний наявна залишки залишок фото фотографії ще це цей ця цієї цього той того такі таке такий така вони їх них для на до від за з із зі по про артикул артикулу артикулом sku код коду кодом товар товари товару товарів варіант варіанти варіантів'));
        $terms = [];
        foreach ($matches[0] as $word) {
            if (isset($ignored[$word]) || mb_strlen($word) < 2) {
                continue;
            }
            $variants = match (true) {
                preg_match('~^(тапк|тапоч|капц|капчик)[а-яіїєґ]*$~u', $word) === 1 => ['тапк', 'тапоч', 'капц', 'капчик'],
                preg_match('~^чорн[а-яіїєґ]*$~u', $word) === 1 => ['чорн'],
                preg_match('~^беж[а-яіїєґ]*$~u', $word) === 1 => ['беж'],
                preg_match('~^біл[а-яіїєґ]*$~u', $word) === 1 => ['біл'],
                preg_match('~^сір[а-яіїєґ]*$~u', $word) === 1 => ['сір'],
                preg_match('~^рожев[а-яіїєґ]*$~u', $word) === 1 => ['рожев'],
                preg_match('~^син(і|ь|я|ю)[а-яіїєґ]*$~u', $word) === 1 => ['син'],
                preg_match('~^червон[а-яіїєґ]*$~u', $word) === 1 => ['червон'],
                preg_match('~^коричнев[а-яіїєґ]*$~u', $word) === 1 => ['коричнев'],
                default => [str_replace(['–', '—'], '-', $word)],
            };
            $terms[implode('|', $variants)] = $variants;
        }

        return array_slice(array_values($terms), 0, 8);
    }
}
